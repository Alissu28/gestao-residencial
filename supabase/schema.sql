-- =========================================================
-- CASA EM ORDEM — Estrutura do banco (Supabase / PostgreSQL)
-- =========================================================
-- Pode ser executado no SQL Editor do Supabase:
--   • Em um projeto NOVO: cria tudo do zero.
--   • No projeto que JÁ EXISTE: só adiciona o que falta (colunas novas,
--     view, segurança). Nenhuma tarefa, pessoa ou cômodo é apagado.
--
-- ATENÇÃO: a parte 4 (Segurança) remove as políticas de acesso antigas
-- destas tabelas e passa a exigir login. Depois de rodar, só usuários
-- convidados no painel do Supabase conseguem ver e editar os dados.
-- =========================================================


-- ---------------------------------------------------------
-- 1. TABELAS
-- ---------------------------------------------------------
create table if not exists public.membros (
  id         bigint generated by default as identity primary key,
  nome       text not null,
  cor        text not null default '#4f46e5',
  email      text,
  created_at timestamptz not null default now()
);

create table if not exists public.categorias (
  id         bigint generated by default as identity primary key,
  nome       text not null,
  icone      text not null default '🏠',
  created_at timestamptz not null default now()
);

create table if not exists public.tarefas (
  id                 bigint generated by default as identity primary key,
  titulo             text not null,
  membro_id          bigint references public.membros(id) on delete set null,
  categoria_id       bigint references public.categorias(id) on delete set null,
  data_prevista      date not null default current_date,
  turno              text not null default 'Qualquer hora',
  recorrencia        text not null default 'unica',
  concluida          boolean not null default false,
  concluida_em       timestamptz,
  concluida_por      bigint references public.membros(id) on delete set null,
  recorrencia_gerada boolean not null default false,
  dias_semana        smallint[],               -- 0=dom … 6=sáb (repetição "dias da semana")
  rodizio            boolean not null default false,
  pontos             smallint not null default 1,
  observacoes        text,
  created_at         timestamptz not null default now()
);

create table if not exists public.compras (
  id             bigint generated by default as identity primary key,
  item           text not null,
  quantidade     text,
  comprado       boolean not null default false,
  adicionado_por bigint references public.membros(id) on delete set null,
  comprado_por   bigint references public.membros(id) on delete set null,
  comprado_em    timestamptz,
  created_at     timestamptz not null default now()
);

create table if not exists public.subtarefas (
  id         bigint generated by default as identity primary key,
  tarefa_id  bigint not null references public.tarefas(id) on delete cascade,
  titulo     text not null,
  feita      boolean not null default false,
  created_at timestamptz not null default now()
);


-- ---------------------------------------------------------
-- 2. COLUNAS NOVAS (para quem já tem o banco criado)
-- ---------------------------------------------------------
-- E-mail do morador: se for igual ao e-mail do login, o app já sabe quem está usando
alter table public.membros  add column if not exists email text;

-- Evita criar repetição duplicada quando uma tarefa recorrente é desmarcada e marcada de novo
alter table public.tarefas  add column if not exists recorrencia_gerada boolean not null default false;

-- Novas funcionalidades: repetição por dias da semana, rodízio, pontos e observações
alter table public.tarefas  add column if not exists dias_semana smallint[];
alter table public.tarefas  add column if not exists rodizio     boolean  not null default false;
alter table public.tarefas  add column if not exists pontos      smallint not null default 1;
alter table public.tarefas  add column if not exists observacoes text;

-- Tarefas recorrentes que já foram concluídas antes desta versão já geraram a próxima
update public.tarefas
   set recorrencia_gerada = true
 where concluida = true
   and recorrencia in ('diaria', 'semanal')
   and recorrencia_gerada = false;

-- Remover uma pessoa ou cômodo não pode apagar/travar tarefas: as referências viram "sem responsável"/"sem cômodo"
do $$
declare
  ref record;
  nome_fk text;
begin
  for ref in
    select * from (values
      ('tarefas', 'membro_id',      'membros'),
      ('tarefas', 'concluida_por',  'membros'),
      ('tarefas', 'categoria_id',   'categorias'),
      ('compras', 'adicionado_por', 'membros'),
      ('compras', 'comprado_por',   'membros')
    ) as v(tabela, coluna, alvo)
  loop
    for nome_fk in
      select c.conname
        from pg_constraint c
        join pg_attribute a on a.attrelid = c.conrelid and a.attnum = any (c.conkey)
       where c.contype = 'f'
         and c.conrelid = format('public.%I', ref.tabela)::regclass
         and a.attname = ref.coluna
    loop
      execute format('alter table public.%I drop constraint %I', ref.tabela, nome_fk);
    end loop;

    execute format(
      'alter table public.%I add constraint %I foreign key (%I) references public.%I(id) on delete set null',
      ref.tabela, ref.tabela || '_' || ref.coluna || '_fkey', ref.coluna, ref.alvo
    );
  end loop;
end $$;

create index if not exists tarefas_concluida_idx    on public.tarefas (concluida, concluida_em desc);
create index if not exists subtarefas_tarefa_id_idx on public.subtarefas (tarefa_id);


-- ---------------------------------------------------------
-- 3. VIEW DO PLACAR (tarefas e pontos por pessoa nos últimos 7 dias)
-- ---------------------------------------------------------
-- (drop antes do create: a view ganhou a coluna total_pontos)
drop view if exists public.placar_semanal;
create view public.placar_semanal
with (security_invoker = true) as
select
  m.id,
  m.nome,
  m.cor,
  count(t.id)::int                     as total_concluidas,
  coalesce(sum(t.pontos), 0)::int      as total_pontos
from public.membros m
left join public.tarefas t
  on t.concluida_por = m.id
 and t.concluida = true
 and t.concluida_em >= now() - interval '7 days'
group by m.id, m.nome, m.cor
order by total_pontos desc, total_concluidas desc, m.nome;


-- ---------------------------------------------------------
-- 4. SEGURANÇA (Row Level Security): só usuários logados acessam
-- ---------------------------------------------------------
alter table public.membros    enable row level security;
alter table public.categorias enable row level security;
alter table public.tarefas    enable row level security;
alter table public.subtarefas enable row level security;
alter table public.compras    enable row level security;

-- Remove políticas antigas (ex.: as que liberavam acesso para qualquer visitante)
do $$
declare pol record;
begin
  for pol in
    select policyname, tablename
      from pg_policies
     where schemaname = 'public'
       and tablename in ('membros', 'categorias', 'tarefas', 'subtarefas', 'compras')
  loop
    execute format('drop policy %I on public.%I', pol.policyname, pol.tablename);
  end loop;
end $$;

create policy "Moradores logados acessam membros"
  on public.membros for all to authenticated using (true) with check (true);

create policy "Moradores logados acessam categorias"
  on public.categorias for all to authenticated using (true) with check (true);

create policy "Moradores logados acessam tarefas"
  on public.tarefas for all to authenticated using (true) with check (true);

create policy "Moradores logados acessam subtarefas"
  on public.subtarefas for all to authenticated using (true) with check (true);

create policy "Moradores logados acessam compras"
  on public.compras for all to authenticated using (true) with check (true);

-- Visitantes sem login não têm nenhum acesso
revoke all on public.membros, public.categorias, public.tarefas, public.subtarefas, public.compras, public.placar_semanal from anon;


-- ---------------------------------------------------------
-- 5. REALTIME (sincronização ao vivo entre aparelhos)
-- ---------------------------------------------------------
do $$
declare tabela text;
begin
  foreach tabela in array array['membros', 'categorias', 'tarefas', 'subtarefas', 'compras'] loop
    begin
      execute format('alter publication supabase_realtime add table public.%I', tabela);
    exception when duplicate_object then
      null; -- já estava publicada
    end;
  end loop;
end $$;
